#!/usr/bin/env python3
"""Turn results/*.json into the paper's tables and figures.

Every number in the paper comes through here.  Nothing is typed in by hand, so
re-running the experiments re-writes the paper's results, and a figure can never
drift away from the data behind it.

    python research/report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

RESULTS = ROOT / "research" / "results"
TABLES = ROOT / "paper" / "tables"
FIGURES = ROOT / "paper" / "figures"

SYNTHETIC_WARNING = (
    "% GENERATED by research/report.py - do not edit\n"
    "% SOURCE = synthetic.  These numbers verify that the harness runs; they are\n"
    "% NOT evidence about real products and must not be reported as results.\n")


def load(name: str) -> dict | None:
    path = RESULTS / f"{name}.json"
    return json.loads(path.read_text()) if path.exists() else None


def header(result: dict) -> str:
    if result.get("source") == "synthetic":
        return SYNTHETIC_WARNING
    return "% GENERATED by research/report.py - do not edit\n"


def _tex(text: str) -> str:
    """Escape what LaTeX would otherwise read as markup in a plain cell."""
    return (text.replace("\\", "\\textbackslash{}").replace("_", "\\_")
            .replace("%", "\\%").replace("&", "\\&"))


def latex_table(result: dict, columns: list[tuple[str, str, str]], rows: list[dict],
                caption: str, label: str) -> str:
    """columns: (key, heading, format spec)."""
    spec = "l" + "r" * (len(columns) - 1)
    out = [header(result), "\\begin{table}[t]", "\\centering",
           f"\\caption{{{caption}}}", f"\\label{{tab:{label}}}",
           f"\\begin{{tabular}}{{{spec}}}", "\\toprule",
           " & ".join(h for _, h, _ in columns) + " \\\\", "\\midrule"]
    for row in rows:
        cells = []
        for key, _, fmt in columns:
            value = row.get(key)
            cells.append("--" if value is None else format(value, fmt) if fmt else _tex(str(value)))
        out.append(" & ".join(cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(out)


def write(name: str, text: str) -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / f"{name}.tex").write_text(text)
    print(f"  paper/tables/{name}.tex")


# --------------------------------------------------------------------- tables

def table_e2() -> None:
    r = load("E2")
    if not r:
        return
    rows = [{**row, "accuracy_pct": row["accuracy"] * 100,
             "proto_pct": row.get("accuracy_prototype", float("nan")) * 100} for row in r["rows"]]
    write("e2_fewshot", latex_table(
        r, [("k", "Views enrolled ($k$)", ""), ("accuracy_pct", "Nearest view (\\%)", ".1f"),
            ("proto_pct", "Mean prototype (\\%)", ".1f"), ("n_probes", "Probes", "d")], rows,
        caption=("Recognition accuracy against the number of reference views, on products "
                 "the representation never saw during training. A product is scored by "
                 "its nearest reference view (what the till does) or by the mean of its "
                 "views (a prototype classifier)."),
        label="fewshot"))


def table_e3() -> None:
    r = load("E3")
    if not r:
        return
    rows = [{**row, "accuracy_pct": row.get("accuracy", 0) * 100,
             "whitened_pct": row.get("accuracy_whitened", float("nan")) * 100}
            for row in r["rows"] if "error" not in row]
    caption = ("Backbone accuracy against inference cost per crop. Centred: the till's "
               "mean-centred cosine. Whitened: PCA-whitening fitted on the held-out "
               "products (J\\'egou and Chum, 2012).")
    if not r.get("comparable_timings", True):
        caption += " \\textbf{Timings span more than one runtime and are not comparable.}"
    write("e3_backbones", latex_table(
        r, [("backbone", "Backbone", ""), ("dim", "Dim.", "d"), ("runtime", "Runtime", ""),
            ("accuracy_pct", "Centred (\\%)", ".1f"), ("whitened_pct", "Whitened (\\%)", ".1f"),
            ("ms_per_crop", "ms / crop", ".1f")],
        rows, caption=caption, label="backbones"))


def table_e4() -> None:
    r = load("E4")
    if not r:
        return
    rows = [{**row, "accuracy_pct": row["accuracy"] * 100} for row in r["rows"]]
    write("e4_temporal", latex_table(
        r, [("frames", "Frames voted", "d"), ("accuracy_pct", "Accuracy (\\%)", ".1f"),
            ("n_scans", "Scans", "d")], rows,
        caption="Accuracy against the number of frames combined into one decision.",
        label="temporal"))


def table_e5() -> None:
    r = load("E5")
    if not r:
        return
    if r.get("insufficient_data"):
        write("e5_openset", header(r) +
              "% NOT RUN: " + r["error"].replace("\n", " ") + "\n")
        return
    names = {"max_cosine": "Nearest reference (ours)", "energy": "Energy score",
             "msp": "Max softmax probability"}
    scores = r.get("scores") or {"max_cosine": r}
    rows = [{"rule": names.get(k, k), "auroc": v["auroc"], "fpr95": v["fpr_at_95_tpr"],
             "tpr": v["tpr"], "fpr": v["fpr"]} for k, v in scores.items()]
    write("e5_openset", latex_table(
        r, [("rule", "Abstention rule", ""), ("auroc", "AUROC", ".3f"),
            ("fpr95", "FPR@95TPR", ".3f"), ("tpr", "TPR at $\\tau$", ".3f"),
            ("fpr", "FPR at $\\tau$", ".3f")], rows,
        caption=("Telling an enrolled product from one the shop does not stock, under three "
                 "abstention rules over the same similarity vectors. A closed-set classifier "
                 "cannot express this decision at all."),
        label="openset"))


def table_e6() -> None:
    r = load("E6")
    if not r:
        return
    ident = [{**row, "accuracy_pct": row["accuracy"] * 100,
              "ambiguous_pct": row["ambiguous_rate"] * 100} for row in r["identification"]]
    write("e6_fusion", latex_table(
        r, [("modalities", "Modalities", ""), ("accuracy_pct", "Accuracy (\\%)", ".1f"),
            ("ambiguous_pct", "Referred to operator (\\%)", ".1f")], ident,
        caption="What each sensing modality contributes to identification.",
        label="fusion"))

    swap = [{**row, "detected_pct": row["swaps_detected"] * 100,
             "false_pct": row["false_alarm_rate"] * 100} for row in r["item_swap"]]
    write("e6_swap", latex_table(
        r, [("k_sigma", "$k_\\sigma$", ".1f"),
            ("tolerance_1_item_g", "Tolerance, 1 item (g)", ".1f"),
            ("detected_pct", "Swaps detected (\\%)", ".1f"),
            ("false_pct", "False alarms (\\%)", ".1f")], swap,
        caption=("Item-swap detection against the weight tolerance. $k_\\sigma$ trades "
                 "security against accusing honest customers."),
        label="swap"))


def table_e9() -> None:
    """One row per public dataset and k; the datasets come from E9-<tag>.json files."""
    results = [json.loads(p.read_text()) for p in sorted(RESULTS.glob("E9*.json"))]
    if not results:
        return
    rows, openset = [], []
    for r in results:
        dataset = r["source"].split(":", 1)[-1]
        for x in r["fewshot"]:
            rows.append({"dataset": dataset, "k": x["k"], "accuracy_pct": x["accuracy"] * 100,
                         "proto_pct": x["accuracy_prototype"] * 100,
                         "n_probes": x["n_probes"], "n_skus": x["n_skus"]})
        for rule, v in (r.get("openset", {}).get("scores") or {}).items():
            openset.append({"dataset": dataset, "rule": rule, "auroc": v["auroc"],
                            "fpr95": v["fpr_at_95_tpr"], "tau": v["threshold"]})
    write("e9_public", latex_table(
        results[0],
        [("dataset", "Dataset", ""), ("k", "$k$", ""), ("n_skus", "SKUs scored", "d"),
         ("accuracy_pct", "Top-1 (\\%)", ".1f"), ("proto_pct", "Prototype (\\%)", ".1f"),
         ("n_probes", "Probes", "d")], rows,
        caption=("Few-shot accuracy on the Grocery Store dataset (whole photograph as the "
                 "crop; scored on the half of the classes held out as unseen). "
                 "\\emph{iconic}: the manufacturer image is the first reference view."),
        label="public"))
    if openset:
        write("e9_public_openset", latex_table(
            results[0],
            [("dataset", "Dataset", ""), ("rule", "Abstention rule", ""), ("auroc", "AUROC", ".3f"),
             ("fpr95", "FPR@95TPR", ".3f"), ("tau", "$\\tau$@95TPR", ".3f")], openset,
            caption="Open-set rejection on the Grocery Store dataset.", label="publicopenset"))


def table_e7() -> None:
    r = load("E7")
    if not r:
        return
    rows = [{"metric": "Baskets priced exactly right (\\%)", "value": r["exact_match_rate"] * 100},
            {"metric": "Mean absolute error (THB)", "value": r["mean_abs_error_baht"]},
            {"metric": "Worst basket error (THB)", "value": r["max_abs_error_baht"]},
            {"metric": "Mean signed error (THB)", "value": r["mean_signed_error_baht"]}]
