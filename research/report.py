def table_e8() -> None:
    r = load("E8")
    if not r:
        return
    retrain_h = r.get("closed_set_retrain_hours")
    rows = [{"method": "Proposed: enrol from $k$ views", "cost": r["total_seconds_estimate"] / 60.0},
            {"method": "Closed set: photograph, label, retrain",
             "cost": retrain_h * 60.0 if retrain_h else None}]
    write("e8_enrolment", latex_table(
        r, [("method", "Adding one product", ""), ("cost", "Minutes", ".1f")], rows,
        caption=("The cost of putting one new product on sale. The closed-set figure is "
                 "the team's own record of building the version~1 model, not an estimate."),
        label="enrolment"))


# -------------------------------------------------------------------- figures

def figures() -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    FIGURES.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({"figure.figsize": (4.2, 3.0), "font.size": 9,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "savefig.bbox": "tight", "savefig.dpi": 200})

    r2 = load("E2")
    if r2:
        fig, ax = plt.subplots()
        ax.plot([x["k"] for x in r2["rows"]], [x["accuracy"] * 100 for x in r2["rows"]],
                marker="o", color="#0B5FFF")
        ax.set_xlabel("reference views per product ($k$)")
        ax.set_ylabel("top-1 accuracy (%)")
        ax.set_ylim(0, 101)
        ax.grid(alpha=.3)
        if r2.get("source") == "synthetic":
            ax.set_title("SYNTHETIC - harness check, not a result", fontsize=7, color="#B3261E")
        fig.savefig(FIGURES / "e2_fewshot.pdf")
        plt.close(fig)
        print("  paper/figures/e2_fewshot.pdf")

    r3 = load("E3")
    if r3:
        rows = [x for x in r3["rows"] if "error" not in x]
        fig, ax = plt.subplots()
        for x in rows:
            ax.scatter(x["ms_per_crop"], x["accuracy"] * 100, s=42, color="#0B5FFF")
            ax.annotate(x["backbone"].replace("_", " "), (x["ms_per_crop"], x["accuracy"] * 100),
                        textcoords="offset points", xytext=(6, -3), fontsize=7)
        ax.set_xlabel("inference cost (ms per crop)")
        ax.set_ylabel("top-1 accuracy (%)")
        ax.grid(alpha=.3)
        if not r3.get("comparable_timings", True):
            ax.set_title("timings not comparable across runtimes", fontsize=7, color="#B3261E")
        fig.savefig(FIGURES / "e3_backbones.pdf")
        plt.close(fig)
        print("  paper/figures/e3_backbones.pdf")

    r6 = load("E6")
    if r6:
        fig, ax = plt.subplots()
        rows = r6["item_swap"]
        ax.plot([x["tolerance_1_item_g"] for x in rows],
                [x["swaps_detected"] * 100 for x in rows], marker="o",
                color="#0B5FFF", label="swaps detected")
        ax.plot([x["tolerance_1_item_g"] for x in rows],
                [x["false_alarm_rate"] * 100 for x in rows], marker="s",
                color="#B3261E", label="false alarms")
        ax.set_xlabel("weight tolerance for a one-item basket (g)")
        ax.set_ylabel("%")
        ax.legend(frameon=False)
        ax.grid(alpha=.3)
        fig.savefig(FIGURES / "e6_swap.pdf")
        plt.close(fig)
        print("  paper/figures/e6_swap.pdf")


def main() -> int:
    if not RESULTS.exists():
        print("no results yet - run:  python research/run.py")
        return 1
    sources = {json.loads(p.read_text()).get("source") for p in RESULTS.glob("*.json")}
    print(f"regenerating from results in {sources}\n")
    for fn in (table_e2, table_e3, table_e4, table_e5, table_e6, table_e7, table_e8, table_e9):
        fn()
    figures()
    if "synthetic" in sources:
        print("\n  NOTE: some results are synthetic. Every generated file says so at the top.")
        print("  Real numbers need a capture session: python research/capture.py --help")
    return 0


if __name__ == "__main__":
    sys.exit(main())
